def fmt_wind(speed, runtime):
    """A wind speed with its unit as the display language writes it:
    "12km/h", "12 km/sa", "12mph"."""
    sep = _s("metric_unit_sep", runtime) if runtime.metric else ""
    return f"{speed:.0f}{sep}{runtime.wind_unit_label}"


def _s(key, runtime, **kwargs):
    """Look up a localized string, with optional format substitution."""
    lang = lang_of(runtime)
    if lang == "el" and key + "_one" in _STRINGS[lang]:
        # "στη 1", but "στις 2": also accept 01:00 and compact tooltip
        # times such as 1:30p. The clock format still follows the user.
        import re
        if re.match(r"0?1(?:\D|$)", str(kwargs.get("time", ""))):
            key += "_one"
    return lookup(_STRINGS, key, lang, **kwargs)


def _precip_s(key, code, runtime, **kwargs):
    """A forecast verb agreeing with the precipitation's noun class.

    Swahili manyunyu (drizzle) takes ma-class agreement; mvua (rain)
    and theluji (snow) take i- verb agreement. Choose by weather code
    so editing a description does not change its grammar.
    """
    lang = lang_of(runtime)
    if lang == "sw" and code in (51, 53, 55, 56, 57):
        key += "_ma"
    return lookup(_STRINGS, key, lang, **kwargs)


def has_string(key):
    """Whether `key` is a string of the app's, in any language."""
    return key in _STRINGS["en"]
