# What the gauge measured
# ---------------------------------------------------------------------------
def _observed_url(kind: str, code: str, year: int, month: int, final: bool) -> str:
    """A month's file of *kind* ("hry" heights, "dep" deviations): the
    final one, or the preliminary one before it is out."""
    ym = f"{year}{month:02d}"
    if final:
        return f"{JMA_BASE}/kaiyou/data/db/tide/genbo/{year}/{ym}/{kind}{ym}{code}.txt"
    return f"{JMA_BASE}/kaiyou/data/db/tide/sokuho/{ym}/z_{kind}{ym}{code}.txt"


def _observed_month(code: str, year: int, month: int,
                    today: date) -> tuple[list[str], bool]:
    """(lines, final) of what the gauge measured in a month.

    The final file comes out around the 20th of the month after; until
    then, and always for the month still running, the preliminary file
    stands in, kept three hours.  A final file is kept for a month once
    the month after has ended, and for a day before that, so one not out
    yet is asked for again tomorrow.
    """
    first = date(year, month, 1)
    if (year, month) != (today.year, today.month):
        settled = today >= month_after(month_after(first))
        lines = _fetch_lines(cache_dir() / f"jma_obs_{code}_{first:%Y%m}.json",
                             30 * 86400 if settled else 86400,
                             _observed_url("hry", code, year, month, final=True))
        # A settled month with no file is a gauge that was down; there
        # is no preliminary file that old to look for either.
        if lines or settled:
            return lines, True
    return _fetch_lines(cache_dir() / f"jma_obsz_{code}_{first:%Y%m}.json", 3 * 3600,
                        _observed_url("hry", code, year, month, final=False)), False


def _datum_offset(code: str, year: int, month: int, final: bool,
                  observed: list[str], predicted: list[str]) -> int | None:
    """The centimetres that put the gauge's heights on the tide table's
    datum, from a month of *observed* lines, the year's *predicted*
    ones, and the month's deviations; None when there are none to
    compare.  JMA figures the deviations from the table itself, so every
    hour gives the same number, and the median keeps a stray hour from
    mattering."""
    kept = 30 * 86400 if final else 3 * 3600
    tag = "dep" if final else "depz"
    deviations = _fetch_lines(cache_dir() / f"jma_{tag}_{code}_{year}{month:02d}.json", kept,
                              _observed_url("dep", code, year, month, final))
    predicted = {_day(line): _hourly(line) for line in predicted}
    measured = {_day(line): _hourly(line) for line in observed}
    offsets = []
    for line in deviations:
        # The deviation files write the date in full, after four columns
        # to each of the 24 hours.
        try:
            day = date(int(line[96:100]), int(line[100:102]), int(line[102:104]))
        except ValueError:
            continue
        pred, obs = predicted.get(day), measured.get(day)
        if pred is None or obs is None:
            continue
        for hour in range(24):
            try:
                dev = int(line[hour * 4:hour * 4 + 4])
            except ValueError:
                continue
            if pred[hour] is not None and obs[hour] is not None:
                offsets.append(pred[hour] + dev - obs[hour])
    return round(median(offsets)) if offsets else None


def _hourly_ranges(lines: list[str]) -> dict[date, tuple[int, int]]:
    """{day: (lowest, highest)} in cm from hourly heights alone, as the
    preliminary files give: the samples, and the high and low waters
    between them, found with a parabola through each turn and its
    neighbours, as for Open-Meteo's hourly series."""
    from linecast.tides.openmeteo import _extrema
    series = []
    for line in lines:
        day, hourly = _day(line), _hourly(line)
        # A day the file has not filled in yet, or with an hour the gauge
        # missed, would show a range narrower than the water's.
        if day is None or None in hourly:
            continue
        midnight = datetime(day.year, day.month, day.day, tzinfo=JST)
        series.extend((midnight + timedelta(hours=hour), cm)
                      for hour, cm in enumerate(hourly))
    series.sort(key=lambda p: p[0])
    # A parabola fits only three hours in a row, so the series is cut
    # where a day was left out.
    runs, run = [], []
    for point in series:
        if run and point[0] - run[-1][0] != timedelta(hours=1):
            runs.append(run)
            run = []
        run.append(point)
    runs.append(run)
    days = {}
    for run in runs:
        for dt, cm, *_kind in run + _extrema(run):
            lo, hi = days.get(dt.date(), (cm, cm))
            days[dt.date()] = (min(lo, cm), max(hi, cm))
    return days


def _final_ranges(lines: list[str]) -> dict[date, tuple[int, int]]:
    """{day: (lowest, highest)} in cm of the highs and lows a final file
    lists; a day whose turns the gauge missed falls to its hours."""
    days = {}
    for line in lines:
        day = _day(line)
        if day is None:
            continue
        turns = [cm for start in (80, 108) for _dt, cm in _turns(line, day, start)]
        if turns:
            days[day] = (min(turns), max(turns))
    missed = [line for line in lines if _day(line) not in days]
    if missed:
        days.update(_hourly_ranges(missed))
    return days


def fetch_observed_extremes_jma(station_id: str, year: int,
                                today: date) -> dict[date, tuple[float, float]]:
    """{day: (lowest, highest)} of the water the gauge measured in *year*
    before *today*, in feet above the tide table's datum; empty for a
    station JMA does not measure at.

    A month to a request, and one more for the deviations that give the
    datum: thirteen requests for a past year, kept for a month, and as
    many as the months so far for this one.
    """
    code = station_code(station_id)
    first = date(year, 1, 1)
    last = min(date(year, 12, 31), today - timedelta(days=1))
    if code not in GAUGES or last < first:
        return {}
    # The year's table is what ties the gauge's datum to the table's;
    # without it there is nothing to measure against.
    predicted = _fetch_year(code, year)
    if not predicted:
        return {}
    months = []
    for month in range(1, last.month + 1):
        lines, final = _observed_month(code, year, month, today)
        # A gauge that was down still has its file, every column blank
        if any(cm is not None for line in lines for cm in _hourly(line)):
            months.append((month, final, lines))
    offset = None
    for month, final, lines in months:
        offset = _datum_offset(code, year, month, final, lines, predicted)
        if offset is not None:
            break
    if offset is None:
        # Without the deviations there is no saying where the gauge's
        # datum sits, and a pen drawn on the wrong one misleads.
        return {}
    days = {}
    for _month, final, lines in months:
        ranges = _final_ranges(lines) if final else _hourly_ranges(lines)
        for day, (lo, hi) in ranges.items():
            if first <= day <= last:
                days[day] = ((lo + offset) * CM_TO_FT, (hi + offset) * CM_TO_FT)
    return days
