"""Japan Meteorological Agency tide data source.

JMA publishes a year's tide table for each of its stations as a text
file, one fixed-width line a day:

  columns   1-72   the hourly heights, 0h to 23h, three characters each
           73-78   the date as YYMMDD, two characters to a part
           79-80   the station's code
          81-108   up to four high waters, each HHMM and a height
         109-136   up to four low waters, the same

Heights are centimetres above the station's tide-table datum (潮位表
基準面), the mean low water of spring tides and close to chart datum;
this module converts to feet for the NOAA-shaped pipeline.  Times are
JST (UTC+9, no DST).  A slot with no tide in it reads 9999 for its time.
The tables run from 2011, and next year's is published in advance.

About seventy of the stations are JMA's own gauges, and what they
measured is published a month to a file in the same layout: the final
heights, highs and lows about three weeks after the month ends, and
before that the preliminary hourly heights alone.  Those are over the
gauge's own datum (観測基準面), not the table's.  The deviation files,
observed less predicted on the hour, tie the two: the prediction plus
the deviation less the observation comes out the same whole number of
centimetres at every hour of a year, and adding it puts what the gauge
measured on the table's datum.

The station list is JMA's list of tide-table stations, baked below by
scripts/build_jma_tide_stations.py.  The list is in Japanese only, and
the romanized names are on each station's own page, so both are kept: a
reader in Japanese sees the Japanese name, everyone else the romanized.
"""

