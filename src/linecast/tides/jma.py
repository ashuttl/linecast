def _fetch_text(url: str, timeout: float) -> str:
    """The file at *url*, or "" when there is none: a year or month not
    published yet is an answer, kept like any other, so it is not asked
    for again until the cached copy ages out."""
    try:
        return fetch_bytes(url, timeout=timeout).decode("ascii", "replace")
    except HTTPError as exc:
        if exc.code == 404:
            return ""
        raise


def _lines(text: str) -> list[str]:
    # Every file's lines carry the date and code by column 80, which a
    # line cut short in transit would not.
    return [line for line in text.splitlines() if len(line) >= 80]


def _fetch_lines(cache_file, max_age: float, url: str) -> list[str]:
    data = fetch_json_cached(cache_file, max_age, url, timeout=20, fallback=None,
                             fetch=_fetch_text, transform=_lines, provider="tides/jma")
    return data if isinstance(data, list) else []


def _fetch_year(code: str, year: int) -> list[str]:
    """The lines of one year's tide table, or [] when unavailable.

    A past year's predictions never change, so those are kept for 30
    days; the current and coming years for a day, in case JMA revises
    them.
    """
    if year < FIRST_YEAR:
        return []
    max_age = 30 * 86400 if year < datetime.now(JST).year else 86400
    return _fetch_lines(cache_dir() / f"jma_pred_{code}_{year}.json", max_age,
                        f"{JMA_BASE}/kaiyou/data/db/tide/suisan/txt/{year}/{code}.txt")


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------
def _day(line: str) -> date | None:
    try:
        return date(2000 + int(line[72:74]), int(line[74:76]), int(line[76:78]))
    except ValueError:
        return None


def _hourly(line: str) -> list[int | None]:
    """The line's 24 hourly heights in cm; None for an hour the gauge
    missed, which the observed files leave blank."""
    heights = []
    for hour in range(24):
        field = line[hour * 3:hour * 3 + 3].strip()
        try:
            heights.append(int(field))
        except ValueError:
            heights.append(None)
    return heights


def _turns(line: str, day: date, start: int) -> list[tuple[datetime, int]]:
    """Up to four (datetime_jst, cm) turning points from the seven-column
    slots at *start*.  An unused slot reads 9999 for its time, and one
    the gauge missed is blank."""
    out = []
    for slot in range(4):
        field = line[start + slot * 7:start + slot * 7 + 7]
        hhmm = field[:4]
        if not hhmm.strip() or hhmm == "9999":
            continue
        try:
            dt = datetime(day.year, day.month, day.day,
                          int(hhmm[:2]), int(hhmm[2:]), tzinfo=JST)
            out.append((dt, int(field[4:])))
        except ValueError:
            continue
    return out


def parse_hourly(lines: list[str]) -> list[tuple[datetime, float]]:
    """(datetime_jst, height_ft) points from a table's lines."""
    points = []
    dropped = 0
    for line in lines:
        day = _day(line)
        if day is None:
            dropped += 1
            continue
        midnight = datetime(day.year, day.month, day.day, tzinfo=JST)
        for hour, cm in enumerate(_hourly(line)):
            if cm is not None:
                points.append((midnight + timedelta(hours=hour), cm * CM_TO_FT))
    log_skipped("tides/jma", "hourly lines", dropped, len(lines))
    return points


def parse_hilo(lines: list[str]) -> list[tuple[datetime, float, str]]:
    """(datetime_jst, height_ft, "H"/"L") from a table's lines, in time
    order.  JMA lists the highs and lows apart, so nothing is inferred."""
    events = []
    dropped = 0
    for line in lines:
        day = _day(line)
        if day is None:
            dropped += 1
            continue
        for kind, start in (("H", 80), ("L", 108)):
            events.extend((dt, cm * CM_TO_FT, kind) for dt, cm in _turns(line, day, start))
    log_skipped("tides/jma", "high/low lines", dropped, len(lines))
    events.sort(key=lambda e: e[0])
    return events


# ---------------------------------------------------------------------------
# Ranges
# ---------------------------------------------------------------------------
def _years(station_id: str, start_date: date, end_date: date):
    """The table's lines for each year the range touches."""
    code = station_code(station_id)
    if code is None:
        return
    for year in range(start_date.year, end_date.year + 1):
        yield _fetch_year(code, year)


def fetch_tides_range_jma(station_id: str, start_date: date, end_date: date,
                          station_tz: tzinfo | None = None,
                          ) -> list[tuple[datetime, float]]:
    """Hourly predictions from *start_date* through *end_date*, as sorted
    (datetime, height_ft) points.  JMA is always JST, so *station_tz* is
    accepted for the provider interface and not needed."""
    lo, hi = local_day_bounds(start_date, end_date, JST)
    points = []
    for lines in _years(station_id, start_date, end_date):
        points.extend(p for p in parse_hourly(lines) if lo <= p[0] < hi)
    points.sort(key=lambda p: p[0])
    return points


def fetch_hilo_range_jma(station_id: str, start_date: date, end_date: date,
                         station_tz: tzinfo | None = None,
                         ) -> list[tuple[datetime, float, str]]:
    """Highs and lows from *start_date* through *end_date*, as sorted
    (datetime, height_ft, "H"/"L") tuples."""
    lo, hi = local_day_bounds(start_date, end_date, JST)
    events = []
    for lines in _years(station_id, start_date, end_date):
        events.extend(e for e in parse_hilo(lines) if lo <= e[0] < hi)
    events.sort(key=lambda e: e[0])
    return events


def fetch_y_range_jma(station_id: str, center_date: date,
                      station_tz: tzinfo | None = None) -> tuple[float, float] | None:
    """The y-axis range from the highs and lows around *center_date*.
    Cached 7 days, keyed by month like the other providers."""
    code = station_code(station_id)
    if code is None:
        return None
    start, end, key = y_range_window(center_date)

    def heights():
        hilo = fetch_hilo_range_jma(station_id, start, end, station_tz)
        if hilo:
            return [h for _, h, _ in hilo]
        return [h for _, h in fetch_tides_range_jma(station_id, start, end, station_tz)]

    return cached_y_range(cache_dir() / f"jma_yrange_{code}_{key}.json", heights)


