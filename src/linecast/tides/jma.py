def station_code(station_id: str) -> str | None:
    """The two-character JMA code in a "jma:TK" ID, or None."""
    if station_id[:len(ID_PREFIX)].lower() != ID_PREFIX:
        return None
    code = station_id[len(ID_PREFIX):].upper()
    return code if code in STATION_BY_CODE else None


def is_jma_station_id(text: str) -> bool:
    """True for "jma:" and one of the codes above, in any case."""
    return station_code(text) is not None


def _station_id(code: str) -> str:
    return f"{ID_PREFIX}{code}"


def display_name(station: dict[str, Any]) -> str:
    """The station's name in Japanese for a reader in Japanese, else
    romanized.  The provider interface has no runtime to ask, so the
    running command's is read."""
    from linecast._i18n import lang_of
    from linecast._runtime import current_runtime
    if lang_of(current_runtime()) == "ja":
        return station["name_ja"]
    return station["name"]


def find_nearest_station_jma(lat: float, lng: float) -> tuple[str | None, str | None]:
    """The closest station within 100 nm as (id, name), else (None, None).
    The name is looked up afresh, as the reader's language may have
    changed since the pick was cached."""
    station_id, _name = nearest_station(
        cache_dir() / f"jma_station_{location_cache_key(lat, lng)}.json",
        lat, lng, lambda: STATIONS, station_coords,
        lambda s: (_station_id(s["id"]), s["name"]), tag="tides/jma",
    )
    code = station_code(station_id) if station_id else None
    if code is None:
        return None, None
    return station_id, display_name(STATION_BY_CODE[code])


def fetch_station_metadata_jma(station_id: str) -> dict[str, Any] | None:
    """Station metadata in the shape the NOAA pipeline reads."""
    code = station_code(station_id)
    if code is None:
        return None
    s = STATION_BY_CODE[code]
    return {
        "id": _station_id(code),
        "name": display_name(s),
        "state": "JP",
        "lat": s["lat"],
        "lng": s["lng"],
        "timezone_abbr": "JST",
        "timezonecorr": 9,
        "timeZoneCode": "Asia/Tokyo",
        "observedst": False,
        "source": "jma",
    }


